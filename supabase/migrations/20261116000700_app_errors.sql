-- Registro simple de errores del cliente, visible para administradores.

create table if not exists public.app_errors (
  id bigint generated by default as identity primary key,
  message text not null,
  stack text,
  component_stack text,
  route text,
  user_agent text,
  user_id uuid,
  created_at timestamptz not null default now()
);

alter table public.app_errors enable row level security;

drop policy if exists "app_errors_admin_read" on public.app_errors;
create policy "app_errors_admin_read"
on public.app_errors
for select
to authenticated
using (public.is_admin());

create or replace function public.log_client_error(
  p_message text,
  p_stack text default null,
  p_component_stack text default null,
  p_route text default null,
  p_user_agent text default null
)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.app_errors
    (message, stack, component_stack, route, user_agent, user_id)
  values (
    left(coalesce(p_message, 'Error desconocido'), 2000),
    left(p_stack, 8000),
    left(p_component_stack, 8000),
    left(p_route, 500),
    left(p_user_agent, 500),
    auth.uid()
  );
$$;

revoke all on function public.log_client_error(text, text, text, text, text) from public;
grant execute on function public.log_client_error(text, text, text, text, text) to anon, authenticated;
